  /// Retrieves localized string with deterministic fallback:
  /// 1. Look up in [locale]
  /// 2. If missing or blank, look up in 'en'
  /// 3. If missing in 'en', return [key]
  static String get(String key, {String locale = 'en'}) {
    final langMap = _localizedValues[locale] ?? _localizedValues['en']!;
    final val = langMap[key];
    if (val != null && val.isNotEmpty) return val;
    final fallbackVal = _localizedValues['en']?[key];
    if (fallbackVal != null && fallbackVal.isNotEmpty) return fallbackVal;
    return key;
  }

  /// Returns whether a language is fully translation-verified.
  static bool isLanguageReviewed(String code) {
    return supportedLanguages.firstWhere(
      (l) => l.code == code,
      orElse: () => const LanguageItem(code: '', nativeName: '', englishName: '', translationReviewed: false),
    ).translationReviewed;
  }
